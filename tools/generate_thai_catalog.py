"""Compile the reviewed Thai presentation catalogue; no network translation."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]
rows = {}
for line in (ROOT / 'localization/th.tsv').read_text().splitlines():
    en, th = line.split('\t', 1)
    key = en.strip().lower()
    if key in rows and rows[key] != th.strip():
        raise ValueError(f'Conflicting translation: {en}')
    rows[key] = th.strip()
items = list(rows.items())
parts = ['package com.headunit.launcher\n\n// Generated by tools/generate_thai_catalog.py. Edit localization/th.tsv.\ninternal object ThaiCatalog {\n    val entries: Map<String, String> by lazy {\n        buildMap {']
for i in range(0, len(items), 60):
    parts.append(f'            putAll(chunk{i//60}())')
parts += ['        }\n    }']
for i in range(0, len(items), 60):
    parts.append(f'    private fun chunk{i//60}(): Map<String, String> = mapOf(')
    for en, th in items[i:i+60]:
        parts.append('        '+json.dumps(en,ensure_ascii=False).replace('$','\\$')+' to '+json.dumps(th,ensure_ascii=False).replace('$','\\$')+',')
    parts.append('    )')
parts.append('}\n')
(ROOT/'app/src/main/kotlin/com/headunit/launcher/ThaiCatalog.kt').write_text('\n'.join(parts))
print(f'{len(rows)} Thai catalogue entries')
